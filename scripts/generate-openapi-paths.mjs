#!/usr/bin/env node
/**
 * Generates src/lib/openapi-paths.generated.ts from the route files under
 * src/app/api/v1. Curated entries in src/lib/openapi.ts take precedence per
 * method; this file guarantees every implemented route and method is
 * documented, and tests/contract/openapi-routes.test.ts fails CI if the two
 * ever drift. Run: node scripts/generate-openapi-paths.mjs
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = new URL("../src/app/api/v1", import.meta.url).pathname;
const OUT = new URL("../src/lib/openapi-paths.generated.ts", import.meta.url).pathname;

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (name === "route.ts") out.push(full);
  }
  return out;
}

const TAG_BY_SEGMENT = {
  auth: "Auth", health: "Health", csrf: "Auth", openapi: "Health", properties: "Core", buildings: "Core", apartments: "Core", "apartment-types": "Core",
  availability: "Bookings", bookings: "Bookings", "booking-channels": "Bookings", channels: "Bookings", "tour-contracts": "Bookings",
  guests: "Guests", messaging: "Guests", staff: "Staff", housekeeping: "Operations", maintenance: "Operations", fnb: "Operations",
  invoices: "Finance", expenses: "Finance", finance: "Finance", "currency-rates": "Finance", ai: "AI", admin: "Admin", gdpr: "GDPR",
  dashboard: "Core", briefing: "Core", reports: "Finance", notifications: "Core", audit: "Admin", cron: "Admin", rates: "Finance",
  "rate-plans": "Finance", groups: "Bookings", portal: "Guests", pos: "Operations", book: "Online booking", webhooks: "Online booking",
};

const paths = {};
for (const file of walk(ROOT).sort()) {
  const rel = relative(ROOT, file).replace(/\/route\.ts$/, "");
  const apiPath = "/" + rel.replace(/\[(\w+)\]/g, "{$1}");
  const src = readFileSync(file, "utf8");
  const methods = new Set();
  for (const m of src.matchAll(/export (?:async )?function (GET|POST|PUT|PATCH|DELETE)\b/g)) methods.add(m[1]);
  for (const m of src.matchAll(/export const (GET|POST|PUT|PATCH|DELETE)\s*=/g)) methods.add(m[1]);
  if (methods.size === 0) continue;
  const doc = src.match(/\/\*\*\s*\n\s*\*\s*([^\n]+)/);
  const summaryBase = doc ? doc[1].replace(/^\s*(GET|POST|PUT|PATCH|DELETE)\s+\S+\s*/, "").trim() : "";
  const tag = TAG_BY_SEGMENT[rel.split("/")[0]] || "Core";
  const params = [...apiPath.matchAll(/\{(\w+)\}/g)].map((m) => ({ name: m[1], in: "path", required: true, schema: { type: "string", format: "uuid" } }));
  const noAuth = ["/auth/login", "/auth/reset-password", "/csrf", "/health", "/openapi"].includes(apiPath) || apiPath.startsWith("/portal/");
  paths[apiPath] = {};
  for (const method of [...methods].sort()) {
    const op = {
      tags: [tag],
      summary: summaryBase ? `${summaryBase} (${method})` : `${method} ${apiPath}`,
      responses: { "200": { description: "OK" }, "401": { description: "Unauthenticated" }, "403": { description: "Forbidden (role or MFA)" } },
    };
    if (params.length) op.parameters = params;
    if (noAuth) op.security = [];
    if (method !== "GET") op.responses["400"] = { description: "Validation error" };
    paths[apiPath][method.toLowerCase()] = op;
  }
}

const body = `// GENERATED by scripts/generate-openapi-paths.mjs — do not edit by hand.\n// Curated descriptions live in src/lib/openapi.ts and override these per method.\nexport const generatedPaths = ${JSON.stringify(paths, null, 2)} as const;\n`;
writeFileSync(OUT, body);
console.log(`wrote ${Object.keys(paths).length} paths to ${relative(process.cwd(), OUT)}`);
