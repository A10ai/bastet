export const BOOK_STRINGS: Record<BookLocale, BookStrings> = { en, de, pl, ru, cs };

export function isBookLocale(v: string | null | undefined): v is BookLocale {
  return !!v && (BOOK_LOCALES as readonly string[]).includes(v);
}

/** Pick the page language: explicit ?lang=, then the browser's languages, then English. */
export function detectBookLocale(explicit: string | null | undefined, browserLanguages: readonly string[] = []): BookLocale {
  if (isBookLocale(explicit)) return explicit;
  for (const lang of browserLanguages) {
    const short = lang.toLowerCase().slice(0, 2);
    if (isBookLocale(short)) return short;
  }
  return "en";
}

const INTL_LOCALE: Record<BookLocale, string> = { en: "en-GB", de: "de-DE", pl: "pl-PL", ru: "ru-RU", cs: "cs-CZ" };

export function formatMoney(amount: number, currency: string, locale: BookLocale): string {
  try {
    return new Intl.NumberFormat(INTL_LOCALE[locale], { style: "currency", currency, maximumFractionDigits: 2 }).format(amount);
  } catch {
    return `${amount.toFixed(2)} ${currency}`;
  }
}

export function formatDay(isoDate: string, locale: BookLocale): string {
  return new Date(`${isoDate}T00:00:00`).toLocaleDateString(INTL_LOCALE[locale], { weekday: "short", day: "numeric", month: "short", year: "numeric" });
}

export function nightsLabel(n: number, s: BookStrings): string {
  return `${n} ${n === 1 ? s.night : s.nights}`;
}

/** mm:ss for the hold countdown. */
export function formatCountdown(ms: number): string {
  const total = Math.max(0, Math.floor(ms / 1000));
  const m = Math.floor(total / 60);
  const sec = total % 60;
  return `${m}:${sec.toString().padStart(2, "0")}`;
}
